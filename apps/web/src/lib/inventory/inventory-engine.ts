// ---------------------------------------------------------------------------
// Shared tenant-context type — passed explicitly by every caller
// ---------------------------------------------------------------------------

interface TenantContext {
  /** The ID of the user performing the operation. Must be a valid, non-empty user ID. */
  userId: string
  branchId: string
  businessId: string
  /**
   * Whether SHELF_REFILL tasks generated by a LowStockDetected condition are
   * auto-approved at creation time. Sourced from configuration AUTO_APPROVE_LOW_STOCK_REFILL
   * at the call site (notification-engine.ts). Defaults to true when the config
   * is not explicitly set.
   */
  autoApproveLowStockRefill?: boolean
}

